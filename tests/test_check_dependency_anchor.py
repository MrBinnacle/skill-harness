class TestRefusesBumpAboveExactPin:
    """AC2: pydantic-core 2.46.5 -> 2.48.0 refused by pydantic's ==2.46.5 pin.

    Reproduces the 2026-08-17 shape.  The refusal message names the anchor
    (pydantic), the pin (==2.46.5) and the proposed version (2.48.0).
    """

    def test_refuses(self, tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
        req = tmp_path / "requirements-ci.txt"
        req.write_text(
            textwrap.dedent("""\
                pydantic==2.13.5
                pydantic-core==2.46.5
            """),
            encoding="utf-8",
        )
        diff = tmp_path / "changes.diff"
        diff.write_text(
            textwrap.dedent("""\
                --- a/requirements-ci.txt
                +++ b/requirements-ci.txt
                @@ -1,2 +1,2 @@
                -pydantic-core==2.46.5
                +pydantic-core==2.48.0
            """),
            encoding="utf-8",
        )

        with patch(
            "check_dependency_anchor.fetch_pypi_metadata",
            side_effect=lambda pkg, _version: (
                _pydantic_metadata(_PYDANTIC_REQUIRES_DIST_2_46_5) if pkg == "pydantic" else {}
            ),
        ):
            result = main(["--requirements", str(req), "--diff", str(diff)])

        assert result == 1
        err = capsys.readouterr().err
        assert "pydantic" in err
        assert "==2.46.5" in err
        assert "2.48.0" in err
        assert "No published anchor satisfies" in err


