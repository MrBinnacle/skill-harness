class TestParseDiff:
    """parse_diff extracts changed packages with old and new versions."""

    def test_simple_bump(self) -> None:
        diff = textwrap.dedent("""\
            --- a/requirements-ci.txt
            +++ b/requirements-ci.txt
            @@ -1,2 +1,2 @@
            -pydantic-core==2.46.5
            +pydantic-core==2.48.0
        """)
        changes = parse_diff(diff)
        assert "pydantic_core" in changes
        old, new = changes["pydantic_core"]
        assert old == "2.46.5"
        assert new == "2.48.0"

    def test_no_changes(self) -> None:
        diff = textwrap.dedent("""\
            --- a/requirements-ci.txt
            +++ b/requirements-ci.txt
        """)
        assert parse_diff(diff) == {}

    def test_unchanged_line_is_dropped(self) -> None:
        diff = textwrap.dedent("""\
            --- a/requirements-ci.txt
            +++ b/requirements-ci.txt
            @@ -1,2 +1,2 @@
            -pydantic-core==2.46.5
            +pydantic-core==2.46.5
        """)
        assert parse_diff(diff) == {}


class TestCheckExactPinConstraint:
    """check_exact_pin_constraint returns the blocking == pin or None.

    The check is exact-pin only.  A non-== specifier (range or lower bound)
    is out of scope and never blocks: the dependabot group coordinates ranges,
    and the defect this check exists for is the == anchor with nothing new to
    bump to.
    """

    def test_exact_pin_blocks_above(self) -> None:
        requires_dist = ["pydantic-core==2.46.5"]
        pin = check_exact_pin_constraint(requires_dist, "pydantic-core", "2.48.0")
        assert pin == "==2.46.5"

    def test_exact_pin_passes_at_same_version(self) -> None:
        requires_dist = ["pydantic-core==2.46.5"]
        pin = check_exact_pin_constraint(requires_dist, "pydantic-core", "2.46.5")
        assert pin is None

    def test_exact_pin_passes_below_the_pin(self) -> None:
        # The defect is a follower bumped ABOVE an == anchor; a proposed below
        # the pin is not the dependabot bump-up shape, so it is not refused.
        requires_dist = ["pydantic-core==2.49.0"]
        pin = check_exact_pin_constraint(requires_dist, "pydantic-core", "2.48.0")
        assert pin is None

    def test_non_exact_specifier_is_ignored(self) -> None:
        requires_dist = ["pydantic-core>=2.46.5,<2.47.0"]
        pin = check_exact_pin_constraint(requires_dist, "pydantic-core", "2.48.0")
        assert pin is None

    def test_no_requires_dist(self) -> None:
        pin = check_exact_pin_constraint(None, "pydantic-core", "2.48.0")
        assert pin is None

    def test_different_package_ignored(self) -> None:
        requires_dist = ["other-package==1.0.0"]
        pin = check_exact_pin_constraint(requires_dist, "pydantic-core", "2.48.0")
        assert pin is None

    def test_marker_stripped_before_pin_read(self) -> None:
        requires_dist = ['pydantic-core==2.46.5; python_version >= "3.12"']
        pin = check_exact_pin_constraint(requires_dist, "pydantic-core", "2.48.0")
        assert pin == "==2.46.5"


