def test_binomial_tolerance_constants() -> None:
    """Documented lo/hi match exact Binomial(500, 0.05) central 95% mass."""
    assert pytest.approx(0.05) == NOMINAL_ALPHA
    assert FP_COUNT_LO == 16
    assert FP_COUNT_HI == 35
    assert int(binom.ppf(0.025, N_PAIRS, NOMINAL_ALPHA)) == FP_COUNT_LO
    assert int(binom.ppf(0.975, N_PAIRS, NOMINAL_ALPHA)) == FP_COUNT_HI


# ---------------------------------------------------------------------------
# Core A/A harness
# ---------------------------------------------------------------------------


def test_aa_false_positive_rate_within_binomial_tolerance() -> None:
    """N=500 identical-arm sequential runs: FPR inside Binomial(500, 0.05) band.

    Tolerance arithmetic (see module docstring)::

        alpha = 1 - prob_threshold = 0.05
        lo = binom.ppf(0.025, 500, 0.05) = 16
        hi = binom.ppf(0.975, 500, 0.05) = 35
        assert lo <= false_positive_count <= hi

    Outside the band -> WRONG_NUMBER finding + xfail; never retune thresholds.
    """
    result = run_aa_harness()

    assert result.n_pairs == N_PAIRS
    assert result.seed == SEED
    assert sum(result.outcome_counts.values()) == N_PAIRS
    # Two arms per pair.
    assert sum(result.stopping_reason_counts.values()) == 2 * N_PAIRS
    # Only production StoppingReason values.
    assert set(result.stopping_reason_counts).issubset({r.value for r in StoppingReason})

    fp = result.false_positive_count
    assert FP_COUNT_LO <= fp <= FP_COUNT_HI, (
        f"A/A false-positive count {fp} outside binomial tolerance "
        f"[{FP_COUNT_LO}, {FP_COUNT_HI}] for Binomial({N_PAIRS}, {NOMINAL_ALPHA}). "
        f"rate={result.false_positive_rate:.4f}; seed={SEED}. "
        "Do not retune thresholds — file docs/findings with severity WRONG_NUMBER."
    )


def test_aa_harness_is_deterministic() -> None:
    """Same seed yields bit-identical counts (no network, no wall clock)."""
    a = run_aa_harness()
    b = run_aa_harness()
    assert a == b


def test_aa_report_records_rate_and_tolerance() -> None:
    """docs/assurance/aa-report.md records measured rate + tolerance arithmetic."""
    assert _REPORT.is_file(), f"missing A/A report at {_REPORT}"
    text = _REPORT.read_text(encoding="utf-8")
    assert "false-positive" in text.lower() or "false positive" in text.lower()
    assert "0.05" in text or "5%" in text
    assert "binom" in text.lower() or "Binomial" in text
    assert "500" in text
    assert "StoppingReason" in text or "stopping_reason" in text
    assert str(SEED) in text or "163_2026_08_09" in text
    # Measured count from the seeded harness must appear.
    result = run_aa_harness()
    assert str(result.false_positive_count) in text
    for reason in result.stopping_reason_counts:
        assert reason in text
