"""A/A (negative-control) harness for the aggregation two-arm gate (#163).

Offline, seeded, deterministic. Both arms of each paired run are drawn from the
same Bernoulli(p) process and stopped by the production sequential rule, so any
directional ``two_arm_gate`` call is a false positive by construction.

## What is driven

- ``two_arm_gate`` (``aggregation/two_arm.py``) — the two-arm posterior-difference
  significance gate (DIF K7). Registered constants used here match the existing
  two-arm suite: ``delta=0.1``, ``prob_threshold=0.95``.
- Observation generation mirrors ``ablation/runner.py``: ``BetaBinomialAccumulator``
  + ``check_stop()`` / ``next_check_at()`` with ``N_MIN=8``, ``N_INC=4``,
  ``N_MAX=40``. No fixed-n draws.

``aggregate_skill`` (``engine.py``) is the DB orchestrator over already-stopped
verdicts; it does not own a two-arm significance threshold. The A/A estimand is
the two-arm gate's false-positive rate under identical arms. Engine numerics that
matter for pass/fail (Beta posterior mass) are the same primitives exercised by
the sequential stopper and by ``two_arm_gate``.

## Tolerance arithmetic (N=500, nominal alpha = 1 - prob_threshold = 0.05)

Under a well-calibrated gate the false-positive count ``X`` is modelled as
``X ~ Binomial(N=500, alpha=0.05)``. The acceptance band is the central 95%
probability mass of that binomial (exact, via ``scipy.stats.binom.ppf``):

    lo = binom.ppf(0.025, n=500, p=0.05)   # = 16
    hi = binom.ppf(0.975, n=500, p=0.05)   # = 35
    E[X] = 500 * 0.05 = 25

Assert ``lo <= X <= hi``. This is a Monte-Carlo check that the observed FPR sits
near nominal - not a claim that the Bayesian gate is a frequentist level-alpha
test at every (n, delta). If ``X`` falls outside, do **not** retune thresholds:
file a finding (severity WRONG_NUMBER), xfail with a pointer, record seed + count.

## Sequential-stopping requirement

Each arm is generated by:

    acc = BetaBinomialAccumulator()
    next_at = N_MIN
    while True:
        while acc.n < next_at and acc.n < N_MAX:
            acc.add(Bernoulli(p) in {0.0, 1.0})  # no ties in this harness
        decision = acc.check_stop()
        if decision.should_stop:
            break
        next_at = next_check_at(acc.n)

Stopped ``(w, n)`` for treatment and control feed ``two_arm_gate``. Each arm's
``StoppingReason`` is tallied for the report.
"""

