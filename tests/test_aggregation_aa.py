# ---------------------------------------------------------------------------
# Sequential arm simulation (mirrors ablation/runner.py stop loop)
# ---------------------------------------------------------------------------


def _run_arm_sequential(rng: np.random.Generator, p: float) -> StopDecision:
    """Draw Bernoulli(p) observations through the real sequential stopper."""
    acc = BetaBinomialAccumulator()
    next_at = N_MIN
    decision: StopDecision | None = None
    while acc.n < N_MAX:
        target = min(next_at, N_MAX)
        while acc.n < target:
            obs = 1.0 if float(rng.random()) < p else 0.0
            acc.add(obs)
        decision = acc.check_stop()
        if decision.should_stop:
            return decision
        next_at = next_check_at(acc.n)
        if next_at > N_MAX:
            break
    if decision is None:
        decision = acc.check_stop()
    return decision


@dataclass(frozen=True)
class AAResult:
    """Summary of one full A/A Monte Carlo."""

    n_pairs: int
    false_positive_count: int
    false_positive_rate: float
    outcome_counts: dict[str, int]
    stopping_reason_counts: dict[str, int]
    seed: int
    delta: float
    prob_threshold: float
    nominal_alpha: float
    fp_count_lo: int
    fp_count_hi: int


def run_aa_harness(
    *,
    n_pairs: int = N_PAIRS,
    seed: int = SEED,
    p: float = NULL_P,
    delta: float = DELTA,
    prob_threshold: float = PROB_THRESHOLD,
) -> AAResult:
    """Run ``n_pairs`` identical-arm sequential A/A comparisons."""
    rng = np.random.default_rng(seed)
    outcome_counts: Counter[str] = Counter()
    stopping_reason_counts: Counter[str] = Counter()
    fp = 0

    for _ in range(n_pairs):
        treatment = _run_arm_sequential(rng, p)
        control = _run_arm_sequential(rng, p)

        for arm in (treatment, control):
            reason = arm.stopping_reason
            assert reason is not None
            stopping_reason_counts[reason.value] += 1

        # Binary observations => w is integer-valued; cast for the int API.
        t_pass = int(treatment.w_accumulator)
        c_pass = int(control.w_accumulator)
        t_n = treatment.n_samples
        c_n = control.n_samples
        assert t_n >= 1 and c_n >= 1
        assert 0 <= t_pass <= t_n and 0 <= c_pass <= c_n

        gate = two_arm_gate(
            t_pass,
            t_n,
            c_pass,
            c_n,
            delta=delta,
            prob_threshold=prob_threshold,
        )
        outcome_counts[gate.outcome.value] += 1
        if gate.outcome is not TwoArmOutcome.NULL:
            fp += 1

    return AAResult(
        n_pairs=n_pairs,
        false_positive_count=fp,
        false_positive_rate=fp / n_pairs,
        outcome_counts=dict(outcome_counts),
        stopping_reason_counts=dict(stopping_reason_counts),
        seed=seed,
        delta=delta,
        prob_threshold=prob_threshold,
        nominal_alpha=1.0 - prob_threshold,
        fp_count_lo=int(binom.ppf(0.025, n_pairs, 1.0 - prob_threshold)),
        fp_count_hi=int(binom.ppf(0.975, n_pairs, 1.0 - prob_threshold)),
    )


